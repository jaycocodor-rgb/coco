# 평가 제외(휴직·소속 미지정)
LEAVE = {x['성명'] for x in d['hrMaster']['leave']}
TGT = [e for e in E if e['소속'] and e['소속'] != '미지정' and e['성명'] not in LEAVE]

PEER_MAX = 4          # 동료 평가자 상한
def is_mgr(e):        # 직책 보유자 = 하향평가 주체
    return e['직책'] not in ('님', '-', 'None', None, '')

dept = collections.defaultdict(list)
for e in TGT: dept[e['소속']].append(e)

rows, n_self, n_up, n_peer, n_down = [], 0, 0, 0, 0
for dn, mem in sorted(dept.items(), key=lambda kv: -len(kv[1])):
    mgr = [m for m in mem if is_mgr(m)]
    peer = min(PEER_MAX, max(0, len(mem) - 1))
    # 대상 1명당: 자기 1 + 상사 1(상사 있는 부서) + 동료 peer + (관리자면 부하 len-1)
    up   = len(mem) if mgr else 0
    down = sum(len(mem) - 1 for _ in mgr) if mgr else 0
    tot  = len(mem) * (1 + peer) + up + down
    rows.append({'소속': dn, '대상': len(mem), '관리자': len(mgr),
                 '상향평가': up, '동료평가': len(mem) * peer, '하향평가': down,
                 '자기평가': len(mem), '총응답': tot,
                 '1인평균응답': round(tot / len(mem), 1),
                 '관리자공석': len(mgr) == 0})
    n_self += len(mem); n_up += up; n_peer += len(mem) * peer; n_down += down

TOTAL = sum(r['총응답'] for r in rows)
