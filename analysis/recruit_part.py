def parse(fn):
    if fn in OVERRIDE: return OVERRIDE[fn]
    base = re.sub(r'\.(pdf|docx?|jpg|png)$','',fn, flags=re.I)
    base = re.sub(r'\s*\(\d+\)$','',base).strip()
    base = base.replace('001','')
    if base.startswith('이력서_'):
        p = base[4:].split('_'); return ('_'.join(p[:-1]) or None, p[-1])
    if '_' in base:
        job, rest = base.split('_',1)
        nm = re.sub(r'\s*(이력서|자소서이력서|지원서).*$','',rest).strip()
        return (job.strip(), nm or None)
    m = re.match(r'^(.*?)\s+(\S+)\s*(이력서|지원서)', base)
    if m: return (m.group(1).strip() or None, m.group(2))
    return (None, re.sub(r'\s*(이력서|지원서).*$','',base).strip())

