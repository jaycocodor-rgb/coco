def num(v):
    """급여대장에 '1,234,567' 이나 '#N/A' 가 섞여 있어 숫자로 정규화한다."""
    if v in (None, '', '-'):
        return None
    if isinstance(v, str) and v.strip() in ('None', 'nan', '#N/A', '#REF!'):
        return None   # 빈칸이 문자열로 직렬화된 것 — 0으로 본다
    if isinstance(v, (int, float)):
        return float(v)
    t = str(v).replace(',', '').replace('원', '').strip()
    try:
        return float(t)
    except ValueError:
        return None


def pay_of(r):
    """지급 항목을 직접 합산한다. 읽지 못한 칸 수도 함께 돌려준다."""
    tot = irr = na = 0
    for c in PAYCOLS:
        if c not in r:
            continue
        v = num(r.get(c))
        if v is None:
            if str(r.get(c)).strip() not in ('', '-', 'None', 'nan'):
                na += 1   # 진짜 판독 불가(#N/A 등)만 센다
            continue
        tot += v
        if c in IRREG:
            irr += v
    return tot, irr, na


