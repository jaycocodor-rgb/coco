# 직군별 격차 — 계약 대비 실제로 얼마나 더 나가나
def band(rows, label):
    c = sum(r['현재_계약연봉'] or 0 for r in rows)
    a = sum(r['현재_실지급연봉'] or 0 for r in rows)
    g = sum(r['현재_정기연봉'] or 0 for r in rows)
    return {'구분': label, '인원': len(rows), '계약연봉': c, '실지급연봉': a, '정기연봉': g,
            '격차': g - c, '격차율': round((g - c) / c, 4) if c else None,
            '1인평균_계약': round(c / len(rows)) if rows else 0,
            '1인평균_정기': round(g / len(rows)) if rows else 0,
            '1인평균_실지급': round(a / len(rows)) if rows else 0}

